// Gathers bench/results/*.json into bench/report/data.js (window.BENCH), which index.html reads. A script file,
// not fetch(), so the page also opens straight from disk (file://).
//   node bench/report/build.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BENCH, readJson as readJsonFile, RESULTS, tasks } from "../lib.mjs";

const suite = tasks();
const files = (() => {
  try {
    return readdirSync(RESULTS).filter((f) => f.endsWith(".json"));
  } catch {
    return [];
  }
})();

const runs = files
  .map((f) => JSON.parse(readFileSync(join(RESULTS, f), "utf8")))
  .filter((r) => r.round === suite.round && r.tasks?.length)
  .sort((a, b) => a.started_at.localeCompare(b.started_at));

// The latest complete run per agent + model + effort + arm; incomplete or older ones stay in "all runs".
const key = (r) => `${r.agent}|${r.model}|${r.effort ?? ""}|${r.arm}`;
const latest = new Map();
// A task whose session never started (usage limit, API error) makes the run incomplete, not a zero: resume it.
const complete = (r) => r.tasks.length === suite.tasks.length && !r.tasks.some((t) => t.is_error && t.tool_calls === 0);
for (const r of runs) if (complete(r)) latest.set(key(r), r);

const sum = (xs, f) => xs.reduce((s, x) => s + (f(x) ?? 0), 0);
function summarize(r) {
  const t = r.tasks;
  const score = sum(t, (x) => x.score.got);
  const max = sum(t, (x) => x.score.max);
  const tokens = sum(t, (x) => x.input_tokens + x.output_tokens);
  const wall = sum(t, (x) => x.wall_ms);
  const cost = t.every((x) => x.cost_usd == null) ? null : sum(t, (x) => x.cost_usd);
  const diff = { kolay: 0, orta: 0, zor: 0, none: 0 };
  for (const x of t) diff[x.difficulty ?? "none"]++;
  const conf = t.filter((x) => x.confidence != null);
  return {
    run_id: r.run_id,
    agent: r.agent,
    model: r.model,
    model_resolved: r.model_resolved ?? null,
    effort: r.effort,
    arm: r.arm,
    started_at: r.started_at,
    score,
    max,
    pct: max ? score / max : 0,
    tokens,
    input_tokens: sum(t, (x) => x.input_tokens),
    cached_input_tokens: sum(t, (x) => x.cached_input_tokens),
    output_tokens: sum(t, (x) => x.output_tokens),
    wall_ms: wall,
    cost_usd: cost,
    tool_calls: sum(t, (x) => x.tool_calls),
    tool_errors: sum(t, (x) => x.tool_errors),
    cortex_calls: sum(t, (x) => x.cortex_calls),
    cli: r.cli ?? null,
    voided: t.filter((x) => x.voided).length,
    peeked: t.filter((x) => !x.voided && x.outside?.length).length,
    failed_sessions: t.filter((x) => x.is_error || x.timed_out).length,
    // Time spent on tasks that ended under half marks: the work that did not pay off.
    wasted_ms: sum(
      t.filter((x) => x.score.got < x.score.max / 2),
      (x) => x.wall_ms,
    ),
    points_per_100k: tokens ? (score / tokens) * 100_000 : 0,
    sec_per_point: score ? wall / 1000 / score : null,
    difficulty: diff,
    confidence: conf.length ? sum(conf, (x) => x.confidence) / conf.length : null,
    tasks: t.map((x) => ({
      id: x.id,
      got: x.score.got,
      max: x.score.max,
      wall_ms: x.wall_ms,
      tokens: x.input_tokens + x.output_tokens,
      output_tokens: x.output_tokens,
      tool_calls: x.tool_calls,
      tool_errors: x.tool_errors,
      cortex_calls: x.cortex_calls,
      cost_usd: x.cost_usd,
      difficulty: x.difficulty,
      confidence: x.confidence,
      checks: x.score.checks,
      answer: x.answer_excerpt,
      error: x.is_error || x.timed_out,
      outside: x.outside ?? [],
      voided: Boolean(x.voided),
    })),
  };
}

const data = {
  generated_at: new Date().toISOString(),
  round: suite.round,
  title: suite.title,
  fixture: [...latest.values()][0]?.fixture ?? null,
  notes: readJsonFile(join(BENCH, "report", "notes.json")),
  tasks: suite.tasks.map((t) => ({ id: t.id, title: t.title, kind: t.kind, prompt: t.prompt, key: t.key, max: t.checks.reduce((s, c) => s + c.points, 0) })),
  runs: [...latest.values()].map(summarize),
  all_runs: runs.map((r) => ({ run_id: r.run_id, agent: r.agent, model: r.model, arm: r.arm, tasks: r.tasks.length, started_at: r.started_at })),
};

writeFileSync(join(BENCH, "report", "data.js"), `// Generated by bench/report/build.mjs, do not edit.\nwindow.BENCH = ${JSON.stringify(data, null, 1)};\n`);
console.log(`[report] ${data.runs.length} runs -> bench/report/data.js`);
