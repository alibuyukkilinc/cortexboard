// Markdown is for people: paste it into Slack, a PR or a wiki. Table cells are escaped; nothing is truncated silently.
export function reportToMarkdown(r: Report, lang: Lang = "en"): string {
  const t = L[lang];
  const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
  const day = (iso: string) => dayKey(Date.parse(iso), r.period.timezone ?? "UTC");
  const pct = (x: number | null) => (x === null ? "—" : `${Math.round(x * 100)}%`);
  const list = (rows: string[]) => (rows.length ? rows.map((x) => `- ${x}`).join("\n") : `_${t.nothing}_`);
  const T = r.totals;
  const k = r.knowledge;

  const out: string[] = [];
  out.push(
    `# ${t.title}`,
    "",
    `**${t.period}:** ${day(r.period.since)} → ${day(r.period.until)} (${r.period.days} ${t.days}, ${r.period.timezone ?? "UTC"})`,
    "",
  );

  out.push(`## ${t.atAGlance}`, "");
  out.push(`| | |`, `|---|---|`);
  const A = T.activity.logged;
  out.push(
    `| ${t.activity} | ${A.total} (${t.byAi} ${A.ai} · ${t.byHumans} ${A.human}${A.unknown ? ` · ${t.byUnknown} ${A.unknown}` : ""}) · ${T.activity.system.total} ${t.auditEntries} |`,
  );
  out.push(`| ${t.aiChanges} | ${T.ai_logged_changes}${T.ai_changes_without_why ? ` (${T.ai_changes_without_why} ${t.withoutWhy})` : ""} |`);
  out.push(`| ${t.created} | ${T.items_created.total}${fmtTypes(T.items_created.by_type)} |`);
  out.push(`| ${t.closed} | ${T.items_closed.total}${fmtTypes(T.items_closed.by_type)} |`);
  out.push(
    `| ${t.questions} | ${T.questions.asked} ${t.asked} · ${T.questions.answered} ${t.answered}${T.questions.median_answer_hours !== null ? ` · ${t.medianAnswer} ${T.questions.median_answer_hours} ${t.hoursShort}` : ""} |`,
  );
  out.push(`| ${t.decisions} | ${T.decisions.proposed} ${t.proposed} · ${T.decisions.accepted} ${t.accepted} · ${T.decisions.rejected} ${t.rejected} |`);
  out.push(
    `| ${t.approvals} | ${T.approvals.approved} ${t.approved} · ${T.approvals.rejected} ${t.rejected} · ${T.approvals.pending} ${t.pending}${T.approvals.oldest_pending_days !== null ? ` (${t.oldest} ${T.approvals.oldest_pending_days} ${t.daysShort})` : ""} |`,
  );
  out.push(
    `| ${t.knowledge} | ${k.nodes} ${t.nodes} · ${k.with_code_links} ${t.linked} · ${k.git ? `${k.stale} ${t.stale} (${pct(k.stale_ratio)})${k.stale_info ? ` + ${k.stale_info} ${t.staleInfo}` : ""}` : t.noGit} · ${k.undocumented} ${t.undocumented} · ${k.updated_in_period} ${t.updated} |`,
  );
  out.push("");

  if (r.milestones.length) {
    out.push(`## ${t.milestones}`, "", `| ${t.milestone} | ${t.progress} | ${t.target} | ${t.closedInPeriod} |`, "|---|---:|---|---:|");
    for (const m of r.milestones)
      out.push(`| ${esc(m.name)} | ${m.done} / ${m.total} | ${m.target ?? `_${t.noTarget}_`}${m.overdue ? ` **${t.overdue}**` : ""} | ${m.closed_in_period} |`);
    out.push("");
  }
  if (r.epics.length) {
    out.push(
      `## ${t.epics}`,
      "",
      list(
        r.epics.map(
          (e) =>
            `${esc(e.title)} — ${e.done}/${e.total}${e.open ? "" : ` (${t.finished})`}${e.milestone ? ` · ${esc(e.milestone)}` : ""}${e.assignee ? ` · ${e.assignee}` : ""}`,
        ),
      ),
    );
    if (r.epics_total > r.epics.length)
      out.push(`
_+${r.epics_total - r.epics.length} ${t.moreEpics}_`);
    out.push("");
  }

  out.push(`## ${t.whatAiDid}`, "");
  out.push(
    list(
      r.highlights.ai_changes.map(
        (c) =>
          `**${esc(c.summary)}** — ${c.actor}, ${day(c.at)}${c.why ? `\n  - _${esc(c.why)}_` : ""}${c.files?.length ? `\n  - \`${c.files.map(esc).join("`, `")}\`` : ""}`,
      ),
    ),
    "",
  );

  out.push(`## ${t.decisionsMade}`, "", list(r.highlights.decisions.map((d) => `${esc(d.title)} — **${d.status}** (${d.by}, ${day(d.at)})`)), "");
  out.push(
    `## ${t.closedIssues}`,
    "",
    list(r.highlights.closed_issues.map((i) => `${esc(i.title)}${i.resolution ? ` — ${i.resolution}` : ""} (${t.openFor} ${i.days_open} ${t.daysShort})`)),
    "",
  );

  out.push(`## ${t.waiting}`, "");
  out.push(
    `### ${t.blocking}`,
    "",
    list(r.attention.blocking_questions.map((q) => `${esc(q.title)} — ${q.asked_by} → ${q.assignee ?? "—"} (${q.age_days} ${t.daysShort})`)),
    "",
  );
  out.push(
    `### ${t.pendingApprovals}`,
    "",
    list(r.attention.pending_approvals.map((d) => `${esc(d.title)} (${d.kind}) — ${d.proposed_by}, ${d.age_days} ${t.daysShort}`)),
    "",
  );
  out.push(
    `### ${t.issueAging}`,
    "",
    `| | ${r.attention.issue_aging.map((b) => b.bucket).join(" | ")} |`,
    `|---|${r.attention.issue_aging.map(() => "---:").join("|")}|`,
  );
  out.push(`| ${r.attention.open_issues} | ${r.attention.issue_aging.map((b) => b.count).join(" | ")} |`, "");
  out.push(
    `### ${t.staleNodes}`,
    "",
    list(r.attention.stale_nodes.map((s) => `**${s.severity}** \`${s.path}\` ← ${s.files.map((f) => `\`${esc(f)}\``).join(", ")}`)),
    "",
  );
  out.push(`### ${t.undocumentedBranches}`, "", list(r.attention.undocumented.map((p) => `\`${p}\``)), "");

  const rc = r.rule_checks;
  if (rc.counts.entries) {
    const c = rc.counts;
    out.push(
      `## ${t.ruleChecks}`,
      "",
      t.ruleChecksSummary
        .replace("{entries}", String(c.entries))
        .replace("{decisions}", String(c.decisions))
        .replace("{followed}", String(c.followed))
        .replace("{na}", String(c.not_applicable))
        .replace("{broken}", String(c.broken))
        .replace("{unanswered}", String(c.unanswered)),
      "",
      `### ${t.ruleBroken}`,
      "",
      list(
        rc.broken.map(
          (b) =>
            `${esc(b.decision.title)} — ${esc(b.activity.summary)} (${b.activity.actor}, ${day(b.activity.at)})${b.decision.note ? `: ${esc(b.decision.note)}` : ""}`,
        ),
      ),
      "",
      `### ${t.ruleUnanswered}`,
      "",
      list(
        rc.unanswered.map((u) => `${esc(u.activity.summary)} (${u.activity.actor}, ${day(u.activity.at)}): ${u.decisions.map((d) => esc(d.title)).join("; ")}`),
      ),
      "",
    );
  }

  out.push(
    `## ${t.actors}`,
    "",
    `| ${t.actor} | ${t.kind} | ${t.logged} | ${t.writes} | ${t.draftsCol} | ${t.approvalRate} |`,
    "|---|---|---:|---:|---:|---:|",
  );
  for (const a of r.actors)
    out.push(`| ${a.id} | ${a.kind} | ${a.logged} | ${a.writes} | ${a.drafts.approved} / ${a.drafts.rejected} | ${pct(a.approval_rate)} |`);
  out.push("", `_${t.footer}_`, "");
  return out.join("\n");
}

function fmtTypes(by: Record<string, number>): string {
  const parts = Object.entries(by).map(([k, v]) => `${k} ${v}`);
  return parts.length ? ` (${parts.join(", ")})` : "";
}
